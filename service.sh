#!/system/bin/sh
# ============================================================
# 亮度锁定器 - 开机启动脚本
# 作用：系统启动后启动亮度守护进程（后台循环）
# ============================================================

MODDIR=${0%/*}

# 延迟启动，等待系统完全初始化（避免太早抢系统亮度）
sleep 10

# 启动守护进程（后台运行，日志写入模块目录）
nohup sh "$MODDIR/daemon.sh" > "$MODDIR/daemon.log" 2>&1 &
